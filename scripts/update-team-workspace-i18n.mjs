for (const locale of locales) {
  const file = path.join('packages', 'desktop', 'src', 'renderer', 'services', 'i18n', 'locales', locale, 'ide.json');
  const json = JSON.parse(readFileSync(file, 'utf8'));
  json.team ??= {};
  json.team.workspace = locale === 'vi-VN' ? vi : en;
  const output = `${JSON.stringify(json, null, 2)}\n`;
  const result = spawnSync('mtui', ['--json', 'new', file, '--overwrite', '--content-stdin'], {
    input: output,
    encoding: 'utf8',
  });
  if (result.status !== 0) {
    console.error(result.stderr || result.stdout);
    process.exit(result.status ?? 1);
  }
  console.log(`updated ${locale}`);
}
